/**
 * Service terpadu untuk mengambil data hari libur nasional dan cuti bersama.
 * Fungsi ini mengkombinasikan data hardcoded 2024-2030 dan API Nager Date 
 * (sebagai pelengkap/fallback otomatis untuk tahun-tahun lainnya).
 */
export const getHolidays = async () => {
  try {
    const currYear = new Date().getFullYear();
    
    // Tarik API hanya sebagai backup untuk tahun-tahun yang tidak tercover
    const fetchPromises = [];
    if (currYear < 2024 || currYear > 2030) {
      fetchPromises.push(
        fetch(`https://date.nager.at/api/v3/PublicHolidays/${currYear - 1}/ID`).then(r => r.ok ? r.json() : []),
        fetch(`https://date.nager.at/api/v3/PublicHolidays/${currYear}/ID`).then(r => r.ok ? r.json() : []),
        fetch(`https://date.nager.at/api/v3/PublicHolidays/${currYear + 1}/ID`).then(r => r.ok ? r.json() : [])
      );
    }

    let apiData = [];
    if (fetchPromises.length > 0) {
      const results = await Promise.all(fetchPromises);
      apiData = results.flat();
    }

    // Gabungkan data static dan API
    const mergedHolidays = [...apiData, ...INDONESIA_HOLIDAYS].map(h => ({
      date: h.date,
      localName: h.localName || h.name,
      name: h.name || h.localName
    }));

    // Filter duplikat berdasarkan tanggal (utamakan data statis kita jika ada bentrok)
    // Karena kita menyisipkan INDONESIA_HOLIDAYS di akhir array `mergedHolidays`, 
    // Map akan meng-overwrite data API dengan data static kita jika tanggalnya sama.
    const uniqueMap = new Map();
    mergedHolidays.forEach(item => uniqueMap.set(item.date, item));
    
    return Array.from(uniqueMap.values());
  } catch (error) {
    console.warn("API Error, falling back to static holidays:", error);
    return INDONESIA_HOLIDAYS.map(h => ({
      date: h.date,
      localName: h.name,
      name: h.name
    }));
  }
};
